-- CommerceOS / NEXA GEAR - PostgreSQL reference design v1, 2026-10-22
-- Run ONLY in an empty study database. No DROP / CREATE DATABASE / credentials.
-- Django implementation: translate into models + migrations; do not run this
-- alongside migrate. Django owns sessions/groups/permissions/token handling.
-- App must provide UUIDs using uuid.uuid4; timestamps stored with timezone.
BEGIN;

CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL UNIQUE,
 password varchar(128) NOT NULL,
 first_name varchar(150) NOT NULL DEFAULT '',
 last_name varchar(150) NOT NULL DEFAULT '',
 phone varchar(20) NOT NULL DEFAULT '',
 is_active boolean NOT NULL DEFAULT true,
 is_staff boolean NOT NULL DEFAULT false,
 is_superuser boolean NOT NULL DEFAULT false,
 email_verified_at timestamptz,
 last_login timestamptz,
 date_joined timestamptz NOT NULL DEFAULT now(),
 CHECK (email = lower(btrim(email)) AND email <> '')
);

CREATE TABLE addresses (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 recipient_name varchar(150) NOT NULL,
 phone varchar(20) NOT NULL,
 address_line varchar(300) NOT NULL,
 ward varchar(150) NOT NULL,
 province varchar(150) NOT NULL,
 country_code varchar(2) NOT NULL DEFAULT 'VN' CHECK (country_code='VN'),
 is_default boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX addresses_user_idx ON addresses(user_id);
CREATE UNIQUE INDEX addresses_one_default_uq ON addresses(user_id) WHERE is_default;

CREATE TABLE categories (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parent_id bigint REFERENCES categories(id) ON DELETE RESTRICT,
 name varchar(120) NOT NULL,
 code varchar(40) NOT NULL UNIQUE,
 slug varchar(160) NOT NULL UNIQUE,
 image_key varchar(500),
 is_active boolean NOT NULL DEFAULT true,
 sort_order integer NOT NULL DEFAULT 0,
 CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX categories_parent_idx ON categories(parent_id);

CREATE TABLE brands (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(120) NOT NULL,
 slug varchar(160) NOT NULL UNIQUE,
 logo_key varchar(500),
 is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE products (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 brand_id bigint NOT NULL REFERENCES brands(id) ON DELETE RESTRICT,
 name varchar(200) NOT NULL,
 slug varchar(220) NOT NULL UNIQUE,
 short_name varchar(120) NOT NULL,
 badge varchar(40) NOT NULL DEFAULT '',
 accent_color varchar(7) CHECK (accent_color ~ '^#[0-9a-fA-F]{6}$'),
 summary varchar(500) NOT NULL DEFAULT '',
 description text NOT NULL DEFAULT '',
 specifications jsonb NOT NULL DEFAULT '{}'::jsonb,
 status varchar(12) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','archived')),
 warranty_months integer NOT NULL DEFAULT 0 CHECK (warranty_months >= 0),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (jsonb_typeof(specifications)='object')
);
CREATE INDEX products_category_status_idx ON products(category_id,status,id);
CREATE INDEX products_brand_status_idx ON products(brand_id,status,id);
CREATE INDEX products_active_new_idx ON products(created_at DESC,id DESC) WHERE status='active';

CREATE TABLE product_features (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 content varchar(300) NOT NULL,
 sort_order integer NOT NULL DEFAULT 0
);
CREATE INDEX product_features_sort_idx ON product_features(product_id,sort_order,id);

CREATE TABLE product_variants (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 sku varchar(64) NOT NULL UNIQUE,
 option_key varchar(220) NOT NULL,
 color varchar(60) NOT NULL DEFAULT '',
 switch_type varchar(60) NOT NULL DEFAULT '',
 connection varchar(100) NOT NULL DEFAULT '',
 layout varchar(60) NOT NULL DEFAULT '',
 price numeric(14,0) NOT NULL CHECK (price >= 0),
 compare_at_price numeric(14,0),
 currency varchar(3) NOT NULL DEFAULT 'VND' CHECK (currency='VND'),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(product_id,option_key),
 UNIQUE(id,product_id),
 CHECK (sku=upper(btrim(sku)) AND sku<>''),
 CHECK (option_key<>''),
 CHECK (compare_at_price IS NULL OR compare_at_price >= price)
);
CREATE INDEX variants_product_active_price_idx ON product_variants(product_id,price) WHERE is_active;
CREATE INDEX variants_active_price_idx ON product_variants(price,id) WHERE is_active;

CREATE TABLE product_images (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 variant_id bigint,
 object_key varchar(500) NOT NULL,
 alt_text varchar(250) NOT NULL DEFAULT '',
 width integer NOT NULL CHECK (width>0),
 height integer NOT NULL CHECK (height>0),
 sort_order integer NOT NULL DEFAULT 0,
 is_cover boolean NOT NULL DEFAULT false,
 FOREIGN KEY (variant_id,product_id) REFERENCES product_variants(id,product_id) ON DELETE RESTRICT
);
CREATE INDEX product_images_product_sort_idx ON product_images(product_id,sort_order,id);
CREATE UNIQUE INDEX product_images_cover_uq ON product_images(product_id) WHERE is_cover;

CREATE TABLE home_banners (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title varchar(160) NOT NULL,
 subtitle varchar(300) NOT NULL DEFAULT '',
 desktop_image_key varchar(500) NOT NULL,
 mobile_image_key varchar(500),
 link_path varchar(300) NOT NULL CHECK (link_path LIKE '/%' AND link_path NOT LIKE '//%'),
 starts_at timestamptz,
 ends_at timestamptz,
 is_active boolean NOT NULL DEFAULT true,
 sort_order integer NOT NULL DEFAULT 0,
 CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at>starts_at)
);

CREATE TABLE collections (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(120) NOT NULL,
 slug varchar(160) NOT NULL UNIQUE,
 is_active boolean NOT NULL DEFAULT true,
 sort_order integer NOT NULL DEFAULT 0
);
CREATE TABLE collection_products (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 collection_id bigint NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 sort_order integer NOT NULL DEFAULT 0,
 UNIQUE(collection_id,product_id)
);
CREATE INDEX collection_products_sort_idx ON collection_products(collection_id,sort_order,id);
CREATE INDEX collection_products_product_idx ON collection_products(product_id);

-- Exactly one owner: account OR random guest-token hash. No raw cookie secret stored.
CREATE TABLE carts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id uuid NOT NULL UNIQUE,
 user_id bigint REFERENCES users(id) ON DELETE RESTRICT,
 guest_token_hash varchar(64),
 status varchar(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','converted','merged','expired')),
 expires_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((user_id IS NOT NULL AND guest_token_hash IS NULL) OR (user_id IS NULL AND guest_token_hash IS NOT NULL)),
 CHECK (guest_token_hash IS NULL OR guest_token_hash ~ '^[0-9a-f]{64}$'),
 CHECK (user_id IS NOT NULL OR expires_at IS NOT NULL)
);
CREATE UNIQUE INDEX carts_active_user_uq ON carts(user_id) WHERE user_id IS NOT NULL AND status='active';
CREATE UNIQUE INDEX carts_guest_token_uq ON carts(guest_token_hash) WHERE guest_token_hash IS NOT NULL;
CREATE INDEX carts_expiration_idx ON carts(expires_at) WHERE status='active';

CREATE TABLE cart_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cart_id bigint NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
 variant_id bigint NOT NULL REFERENCES product_variants(id) ON DELETE RESTRICT,
 quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(cart_id,variant_id)
);
CREATE INDEX cart_items_variant_idx ON cart_items(variant_id);

-- V1 one stock location. available = on_hand - reserved; not stored separately.
CREATE TABLE inventory_balances (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 variant_id bigint NOT NULL UNIQUE REFERENCES product_variants(id) ON DELETE RESTRICT,
 on_hand integer NOT NULL DEFAULT 0 CHECK (on_hand>=0),
 reserved integer NOT NULL DEFAULT 0 CHECK (reserved>=0),
 low_stock_threshold integer NOT NULL DEFAULT 5 CHECK (low_stock_threshold>=0),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (reserved<=on_hand)
);

CREATE TABLE vouchers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(40) NOT NULL UNIQUE,
 kind varchar(12) NOT NULL CHECK (kind IN ('percent','fixed','free_ship')),
 value numeric(14,0) NOT NULL,
 max_discount numeric(14,0) CHECK (max_discount>=0),
 min_subtotal numeric(14,0) NOT NULL DEFAULT 0 CHECK (min_subtotal>=0),
 usage_limit integer CHECK (usage_limit>0),
 per_user_limit integer NOT NULL DEFAULT 1 CHECK (per_user_limit>0),
 starts_at timestamptz NOT NULL,
 ends_at timestamptz NOT NULL,
 is_active boolean NOT NULL DEFAULT true,
 CHECK (code=upper(btrim(code)) AND code<>''),
 CHECK (ends_at>starts_at),
 CHECK ((kind='percent' AND value BETWEEN 1 AND 100) OR (kind='fixed' AND value>0) OR (kind='free_ship' AND value=0))
);
ALTER TABLE carts ADD COLUMN voucher_id bigint REFERENCES vouchers(id) ON DELETE SET NULL;
CREATE INDEX carts_voucher_idx ON carts(voucher_id);

CREATE TABLE shipping_methods (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(16) NOT NULL UNIQUE CHECK (code IN ('standard','express')),
 name varchar(120) NOT NULL,
 base_fee numeric(14,0) NOT NULL CHECK (base_fee>=0),
 free_threshold numeric(14,0) CHECK (free_threshold>=0),
 min_days integer NOT NULL CHECK (min_days>=0),
 max_days integer NOT NULL,
 is_active boolean NOT NULL DEFAULT true,
 CHECK (max_days>=min_days)
);

CREATE TABLE orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id uuid NOT NULL UNIQUE,
 order_number varchar(32) NOT NULL UNIQUE,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 checkout_key uuid NOT NULL,
 request_hash varchar(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
 source_cart_id bigint NOT NULL REFERENCES carts(id) ON DELETE RESTRICT,
 status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','packing','shipped','delivered','cancelled','expired')),
 currency varchar(3) NOT NULL DEFAULT 'VND' CHECK (currency='VND'),
 subtotal numeric(14,0) NOT NULL CHECK (subtotal>=0),
 discount_total numeric(14,0) NOT NULL DEFAULT 0 CHECK (discount_total>=0),
 shipping_fee numeric(14,0) NOT NULL DEFAULT 0 CHECK (shipping_fee>=0),
 shipping_discount numeric(14,0) NOT NULL DEFAULT 0 CHECK (shipping_discount>=0),
 grand_total numeric(14,0) NOT NULL CHECK (grand_total>=0),
 voucher_id bigint REFERENCES vouchers(id) ON DELETE RESTRICT,
 voucher_code_snapshot varchar(40),
 shipping_method_id bigint NOT NULL REFERENCES shipping_methods(id) ON DELETE RESTRICT,
 shipping_method_snapshot varchar(120) NOT NULL,
 contact_email_snapshot varchar(254) NOT NULL,
 customer_note varchar(500) NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,checkout_key),
 UNIQUE(source_cart_id),
 UNIQUE(id,user_id),
 CHECK (discount_total<=subtotal),
 CHECK (shipping_discount<=shipping_fee),
 CHECK (grand_total=subtotal-discount_total+shipping_fee-shipping_discount)
);
CREATE INDEX orders_user_created_idx ON orders(user_id,created_at DESC,id DESC);
CREATE INDEX orders_status_created_idx ON orders(status,created_at DESC,id DESC);
CREATE INDEX orders_voucher_idx ON orders(voucher_id);
CREATE INDEX orders_shipping_method_idx ON orders(shipping_method_id);

CREATE TABLE order_addresses (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
 recipient_name varchar(150) NOT NULL,
 phone varchar(20) NOT NULL,
 address_line varchar(300) NOT NULL,
 ward varchar(150) NOT NULL,
 province varchar(150) NOT NULL,
 country_code varchar(2) NOT NULL DEFAULT 'VN' CHECK (country_code='VN')
);

CREATE TABLE order_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
 variant_id bigint NOT NULL REFERENCES product_variants(id) ON DELETE RESTRICT,
 product_name_snapshot varchar(200) NOT NULL,
 sku_snapshot varchar(64) NOT NULL,
 options_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
 quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 unit_price numeric(14,0) NOT NULL CHECK (unit_price>=0),
 line_total numeric(16,0) NOT NULL CHECK (line_total=quantity*unit_price),
 UNIQUE(order_id,variant_id),
 UNIQUE(id,order_id),
 CHECK (jsonb_typeof(options_snapshot)='object')
);
CREATE INDEX order_items_variant_idx ON order_items(variant_id);

CREATE TABLE inventory_reservations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
 variant_id bigint NOT NULL REFERENCES product_variants(id) ON DELETE RESTRICT,
 quantity integer NOT NULL CHECK (quantity>0),
 status varchar(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','consumed','released','expired')),
 expires_at timestamptz NOT NULL,
 closed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(order_id,variant_id),
 CHECK (expires_at>created_at),
 CHECK ((status='active' AND closed_at IS NULL) OR (status<>'active' AND closed_at IS NOT NULL))
);
CREATE INDEX reservations_due_idx ON inventory_reservations(expires_at) WHERE status='active';
CREATE INDEX reservations_variant_idx ON inventory_reservations(variant_id);

CREATE TABLE inventory_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 variant_id bigint NOT NULL REFERENCES product_variants(id) ON DELETE RESTRICT,
 order_id bigint REFERENCES orders(id) ON DELETE RESTRICT,
 actor_id bigint REFERENCES users(id) ON DELETE RESTRICT,
 event_key uuid NOT NULL UNIQUE,
 kind varchar(12) NOT NULL CHECK (kind IN ('receipt','adjustment','sale','return')),
 quantity_delta integer NOT NULL CHECK (quantity_delta<>0),
 reason varchar(300) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((kind IN ('receipt','return') AND quantity_delta>0) OR (kind='sale' AND quantity_delta<0) OR kind='adjustment'),
 CHECK (kind<>'sale' OR order_id IS NOT NULL)
);
CREATE INDEX inventory_movements_variant_time_idx ON inventory_movements(variant_id,created_at DESC,id DESC);
CREATE INDEX inventory_movements_order_idx ON inventory_movements(order_id);
CREATE INDEX inventory_movements_actor_idx ON inventory_movements(actor_id);
CREATE UNIQUE INDEX inventory_sale_once_uq ON inventory_movements(order_id,variant_id) WHERE kind='sale';

CREATE TABLE voucher_redemptions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 voucher_id bigint NOT NULL REFERENCES vouchers(id) ON DELETE RESTRICT,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 order_id bigint NOT NULL UNIQUE,
 status varchar(12) NOT NULL DEFAULT 'reserved' CHECK (status IN ('reserved','used','released')),
 discount_amount numeric(14,0) NOT NULL CHECK (discount_amount>=0),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY (order_id,user_id) REFERENCES orders(id,user_id) ON DELETE RESTRICT
);
CREATE INDEX voucher_redemptions_count_idx ON voucher_redemptions(voucher_id,user_id,status);
CREATE INDEX voucher_redemptions_user_idx ON voucher_redemptions(user_id);

CREATE TABLE order_status_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
 from_status varchar(20) CHECK (from_status IN ('pending','confirmed','packing','shipped','delivered','cancelled','expired')),
 to_status varchar(20) NOT NULL CHECK (to_status IN ('pending','confirmed','packing','shipped','delivered','cancelled','expired')),
 actor_id bigint REFERENCES users(id) ON DELETE RESTRICT,
 reason varchar(300) NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX order_history_order_time_idx ON order_status_history(order_id,created_at,id);
CREATE INDEX order_history_actor_idx ON order_status_history(actor_id);

-- COD only in MVP; fields support future gateway attempts without card data.
CREATE TABLE payments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id uuid NOT NULL UNIQUE,
 order_id bigint NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
 provider varchar(12) NOT NULL CHECK (provider IN ('cod','vnpay','momo')),
 status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','succeeded','failed','cancelled','refunded')),
 amount numeric(14,0) NOT NULL CHECK (amount>=0),
 currency varchar(3) NOT NULL DEFAULT 'VND' CHECK (currency='VND'),
 provider_reference varchar(150),
 idempotency_key uuid NOT NULL UNIQUE,
 paid_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (status NOT IN ('succeeded','refunded') OR paid_at IS NOT NULL)
);
CREATE UNIQUE INDEX payments_provider_ref_uq ON payments(provider,provider_reference) WHERE provider_reference IS NOT NULL;
CREATE UNIQUE INDEX payments_one_success_uq ON payments(order_id) WHERE status IN ('succeeded','refunded');
CREATE UNIQUE INDEX payments_one_pending_uq ON payments(order_id) WHERE status='pending';
CREATE INDEX payments_order_time_idx ON payments(order_id,created_at DESC);

CREATE TABLE wishlists (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,product_id)
);
CREATE INDEX wishlists_product_idx ON wishlists(product_id);

CREATE TABLE audit_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id bigint REFERENCES users(id) ON DELETE RESTRICT,
 action varchar(80) NOT NULL,
 entity_type varchar(80) NOT NULL,
 entity_id varchar(80) NOT NULL,
 request_id uuid NOT NULL,
 changes jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (jsonb_typeof(changes)='object')
);
CREATE INDEX audit_entity_time_idx ON audit_logs(entity_type,entity_id,created_at DESC);
CREATE INDEX audit_actor_time_idx ON audit_logs(actor_id,created_at DESC);

CREATE TABLE outbox_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key uuid NOT NULL UNIQUE,
 topic varchar(100) NOT NULL,
 aggregate_id varchar(100) NOT NULL,
 payload jsonb NOT NULL,
 status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','sent','failed')),
 attempts integer NOT NULL DEFAULT 0 CHECK (attempts>=0),
 available_at timestamptz NOT NULL DEFAULT now(),
 locked_at timestamptz,
 processed_at timestamptz,
 last_error_code varchar(100),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX outbox_pending_idx ON outbox_events(available_at,id) WHERE status='pending';
CREATE INDEX outbox_processing_idx ON outbox_events(locked_at) WHERE status='processing';

-- Product community included in MVP.
CREATE TABLE reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 order_item_id bigint UNIQUE REFERENCES order_items(id) ON DELETE RESTRICT,
 stars smallint NOT NULL CHECK (stars BETWEEN 1 AND 5),
 body varchar(2000) NOT NULL CHECK (length(btrim(body))>=10),
 status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','rejected')),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,product_id)
);
CREATE INDEX reviews_public_product_idx ON reviews(product_id,created_at DESC,id DESC) WHERE status='published';
-- Verified buyer is DERIVED from order_item -> order owner, variant.product_id,
-- and delivered order. Service verifies all links; never accept a client flag.
CREATE TABLE product_questions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 body varchar(2000) NOT NULL CHECK (length(btrim(body))>=5),
 status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','rejected')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX questions_product_idx ON product_questions(product_id,created_at DESC);
CREATE INDEX questions_user_idx ON product_questions(user_id);
CREATE TABLE product_answers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 question_id bigint NOT NULL REFERENCES product_questions(id) ON DELETE RESTRICT,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 body varchar(2000) NOT NULL CHECK (length(btrim(body))>=5),
 status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','rejected')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX answers_question_idx ON product_answers(question_id,created_at);
CREATE INDEX answers_user_idx ON product_answers(user_id);

-- updated_at is maintained by application; bulk updates must set it explicitly.
-- Cross-row invariants (order totals vs lines, reservation sums, voucher quotas,
-- legal status transitions) require the transactional service described in README.
COMMIT;
